export function translateLegacyText(input: string, locale: Locale): string {
  if (locale !== 'en' || !/[一-龥]/.test(input)) {
    return input
  }

  let output = input
  for (const [pattern, replacement] of replacements) {
    output = output.replace(pattern, replacement as never)
  }
  return output
}

function translateAttributes(element: Element, locale: Locale) {
  const attributes = ['placeholder', 'title', 'aria-label']
  for (const attr of attributes) {
    const value = element.getAttribute(attr)
    if (value) {
      const translated = translateLegacyText(value, locale)
      if (translated !== value) {
        element.setAttribute(attr, translated)
      }
    }
  }

  if (element instanceof HTMLInputElement && element.value) {
    const translatedValue = translateLegacyText(element.value, locale)
    if (translatedValue !== element.value && ['button', 'submit', 'reset'].includes(element.type)) {
      element.value = translatedValue
    }
  }
}

export function applyLegacyEnglish(root: ParentNode, locale: Locale) {
  if (locale !== 'en') {
    return
  }

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  const textNodes: Text[] = []

  while (walker.nextNode()) {
    const node = walker.currentNode as Text
    if (!node.parentElement) {
      continue
    }
    const tag = node.parentElement.tagName
    if (['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(tag)) {
      continue
    }
    if (node.nodeValue && /[一-龥]/.test(node.nodeValue)) {
      textNodes.push(node)
    }
  }

  for (const node of textNodes) {
    const current = node.nodeValue || ''
    const translated = translateLegacyText(current, locale)
    if (translated !== current) {
      node.nodeValue = translated
    }
  }

  if (root instanceof Element || root instanceof Document || root instanceof DocumentFragment) {
    const elements = root instanceof Element ? [root, ...root.querySelectorAll('*')] : Array.from(root.querySelectorAll('*'))
    for (const element of elements) {
      translateAttributes(element, locale)
    }
  }
}
